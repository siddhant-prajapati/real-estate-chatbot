def all_seed_properties() -> list[Property]:
    records = []
    for item in DARGLOBAL + WASALT:
        if "bedrooms" not in item and item.get("bedrooms_min") is not None and item.get("bedrooms_max") == item.get("bedrooms_min"):
            item["bedrooms"] = item["bedrooms_min"]
        records.append(Property.model_validate(item))
    return records
